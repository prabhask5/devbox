#!/usr/bin/env python3
"""Bundles contracts/*.schema.json for scripts/gen.sh.

Every schema file defines one root type (its `title`) plus `$defs`. This script merges them into
one document whose `$defs` hold every type, with cross-file references rewritten to local ones:

  internal/proto/schema.gen.json             every type, embedded by the Go validator
  crates/devbox-core/src/proto/schema.json   the same bytes, embedded by the Rust validator
  <argv[1]>                                  input for the code generators, see `resolved`

and writes the contract versions (`x-version`) as constants for Go, Rust and TypeScript.
"""
import glob
import json
import os
import re
import sys

HEADER = "Code generated by scripts/gen.sh from contracts/; DO NOT EDIT."

files = {os.path.basename(p): json.load(open(p)) for p in sorted(glob.glob("contracts/*.schema.json"))}
titles = {name: doc["title"] for name, doc in files.items()}


def rewrite(node):
    """Returns node with every $ref pointing into the bundle's own $defs."""
    if isinstance(node, list):
        return [rewrite(x) for x in node]
    if not isinstance(node, dict):
        return node
    if "$ref" in node:
        # Only the reference survives: the generators treat a reference with a description of its
        # own as a new type.
        file, _, pointer = node["$ref"].partition("#")
        if pointer:
            return {"$ref": "#" + pointer}
        if file in titles:
            return {"$ref": "#/$defs/" + titles[file]}
        sys.exit(f"unresolved $ref {node['$ref']!r}")
    return {k: rewrite(v) for k, v in node.items()}


defs, aliases, versions = {}, [], []
for name, doc in files.items():
    root = {k: v for k, v in doc.items() if k not in ("$schema", "$id", "title", "x-version", "$defs")}
    for title, schema in [(doc["title"], root), *doc.get("$defs", {}).items()]:
        if title in defs:
            sys.exit(f"{name}: type {title} is defined twice")
        defs[title] = rewrite(schema)
    if "$ref" in root:
        aliases.append(doc["title"])
    versions.append((name.removesuffix(".schema.json"), doc["title"], doc["x-version"]))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def bundle(types):
    doc = {"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": dict(sorted(types.items()))}
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def resolved(node):
    """The schema of a value after the loader applied the defaults: a key with a default is
    always present. The generated types describe that value, so code reads `cfg.sleep.idle`
    without asking whether it was set."""
    if isinstance(node, list):
        return [resolved(x) for x in node]
    if not isinstance(node, dict):
        return node
    out = {k: resolved(v) for k, v in node.items() if k != "default"}
    properties = node.get("properties", {})
    defaulted = [k for k, v in properties.items() if isinstance(v, dict) and "default" in v]
    if defaulted:
        out["required"] = node.get("required", []) + defaulted
    return out


write("internal/proto/schema.gen.json", bundle(defs))
write("crates/devbox-core/src/proto/schema.json", bundle(defs))
# Roots that only rename another type get no generated type of their own.
write(sys.argv[1], bundle({name: resolved(schema) for name, schema in defs.items() if name not in aliases}))


def screaming(title):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", title).upper()


go = [f"// {HEADER}", "", "package proto", "", "// Versions of the contracts this build reads and writes.", "const ("]
go += [f"\t{title}Version = {v}" for _, title, v in versions] + [")", ""]
write("internal/proto/versions.gen.go", "\n".join(go))

rs = [f"// {HEADER}", "", "//! Versions of the contracts this build reads and writes.", ""]
for name, title, v in versions:
    rs += [f"/// Version of the `{name}` contract.", f"pub const {screaming(title)}_VERSION: i64 = {v};"]
write("crates/devbox-core/src/proto/versions.rs", "\n".join(rs) + "\n")

ts = [f"// {HEADER}", "", "/** Versions of the contracts this build reads and writes. */"]
ts += [f"export const {screaming(title)}_VERSION = {v};" for _, title, v in versions]
write("web/shared/src/proto/versions.ts", "\n".join(ts) + "\n")
