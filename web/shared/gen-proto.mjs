// Writes src/proto/types.ts from the bundled contracts (run by scripts/gen.sh).
import { readFile, writeFile } from "node:fs/promises";
import { argv } from "node:process";
import { URL } from "node:url";
import { compile } from "json-schema-to-typescript";

const bundle = JSON.parse(await readFile(argv[2], "utf8"));
const generated = await compile(bundle, "Contracts", {
  additionalProperties: false,
  unreachableDefinitions: true,
  bannerComment: "// Code generated by scripts/gen.sh from contracts/; DO NOT EDIT.",
  style: { printWidth: 100 },
});
// The bundle itself is not a type: only its definitions are.
const root = /\nexport interface Contracts \{\n {2}\[k: string\]: unknown;\n\}\n/;
if (!root.test(generated)) throw new Error("the bundle's root type is not where it was expected");
const types = generated
  .replace(root, "")
  .replace(
    /\n \*\n \* This interface was referenced by `Contracts`'s JSON-Schema\n \* via the `definition` "\w+"\./g,
    "",
  )
  .replace(
    /\/\*\*\n \* This interface was referenced by `Contracts`'s JSON-Schema\n \* via the `definition` "\w+"\.\n \*\/\n/g,
    "",
  );
await writeFile(new URL("src/proto/types.ts", import.meta.url), types);
